/**
 * Represents an LLM provider detected in the environment.
 * Can be from BYOK (API keys) or Subscriptions (OAuth).
 */
export interface DetectedProvider {
  id: string;
  type: "byok" | "subscription";
  availableModels: string[];
  capabilities: ("chat" | "embedding" | "rerank" | "decision")[];
}

/**
 * Represents a plugin, skill, MCP, or tool that JYN can manage.
 */
export interface CapabilityEntry {
  id: string;
  name: string;
  type: "plugin" | "mcp" | "skill" | "tool";
  scope: "global" | "workspace";
  description: string;
  triggers: string[]; // e.g., ['react', 'frontend', 'typescript']
  tokensCost: number; // Estimated tokens added to system prompt if active
}

/**
 * The current state of the user's workspace.
 */
export interface WorkspaceProfile {
  path: string;
  techStack: string[]; // e.g., ['python', 'django']
  activePlugins: string[];
  activeMcps: string[];
  activeSkills: string[];
  totalEstimatedTokenCost: number;
}

/**
 * The recommendation generated by JYN's engine.
 */
export interface JynRecommendation {
  action: "enable" | "disable" | "install" | "move-scope";
  targetId: string;
  reason: string;
  estimatedTokenSavings?: number;
}
